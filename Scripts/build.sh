#!/bin/bash
set -euo pipefail
ORBIT_PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
ORBIT_RUNTIME="${ORBIT_RUNTIME:-$ORBIT_PROJECT/.build/orbit}"
ORBIT_APP="$ORBIT_PROJECT/dist/Orbit.app"
ORBIT_SIGN_IDENTITY="${ORBIT_SIGN_IDENTITY:--}"
mkdir -p "$ORBIT_RUNTIME" "$ORBIT_PROJECT/dist"
cd "$ORBIT_PROJECT"
swift build -c release --scratch-path "$ORBIT_RUNTIME/build"
if [ ! -f "$ORBIT_PROJECT/Resources/Orbit.icns" ]; then
    swift "$ORBIT_PROJECT/Scripts/make_icon.swift" "$ORBIT_RUNTIME/Orbit.iconset"
    iconutil -c icns "$ORBIT_RUNTIME/Orbit.iconset" -o "$ORBIT_PROJECT/Resources/Orbit.icns"
fi
mkdir -p "$ORBIT_APP/Contents/MacOS" "$ORBIT_APP/Contents/Resources" "$ORBIT_APP/Contents/Helpers"
cp "$ORBIT_RUNTIME/build/release/Orbit" "$ORBIT_APP/Contents/MacOS/Orbit"
cp "$ORBIT_PROJECT/Resources/Info.plist" "$ORBIT_APP/Contents/Info.plist"
cp "$ORBIT_PROJECT/Resources/Orbit.icns" "$ORBIT_APP/Contents/Resources/Orbit.icns"
cp "$ORBIT_RUNTIME/build/release/OrbitFanAgent" "$ORBIT_APP/Contents/Helpers/OrbitFanAgent"
cp "$ORBIT_RUNTIME/build/release/OrbitUpdateAgent" "$ORBIT_APP/Contents/Helpers/OrbitUpdateAgent"
ditto "$ORBIT_RUNTIME/build/release/Orbit_Orbit.bundle" "$ORBIT_APP/Contents/Resources/Orbit_Orbit.bundle"
printf 'APPL????' > "$ORBIT_APP/Contents/PkgInfo"
codesign --force --options runtime --identifier com.orbitmac.Orbit.FanAgent --sign "$ORBIT_SIGN_IDENTITY" "$ORBIT_APP/Contents/Helpers/OrbitFanAgent"
codesign --force --options runtime --identifier com.orbitmac.Orbit.UpdateAgent --sign "$ORBIT_SIGN_IDENTITY" "$ORBIT_APP/Contents/Helpers/OrbitUpdateAgent"
codesign --force --options runtime --sign "$ORBIT_SIGN_IDENTITY" "$ORBIT_APP"
printf '\n已构建：%s\n' "$ORBIT_APP"
